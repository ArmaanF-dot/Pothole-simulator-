"""State behind the API (M8): scored segments, plan, lights, triage queue, work orders, outcomes.

Kept separate from the FastAPI routes so tests can drive it directly. State that must survive a
restart (queue, feedback, outcomes) is written to outputs/lane_c/.
"""
from __future__ import annotations

import base64
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

from roadsense.agent import triage as TR
from roadsense.prevent import inputs as I
from roadsense.prevent import plan as P
from roadsense.prevent import whatif as W

LICENCES = {
    "segments": "OpenStreetMap contributors, ODbL",
    "risk": "RoadSense risk model (lane B), trained on SYNTHETIC labels",
    "lights": "RoadSense streetlight model (lane B) on a SYNTHETIC lighting register",
    "fixmystreet": "FixMyStreet (mySociety) public reports; location, date, category, title, status only",
    "synthetic": "Generated by RoadSense (seed 2026); replaces council-held data",
    "costs": "ALARM 2025 (Asphalt Industry Alliance), planned £56.94 vs reactive £87.80",
    "forecast": "Open-Meteo forecast, free tier, non-commercial",
}


def _clean(v):
    if isinstance(v, (np.floating, float)):
        return None if not np.isfinite(v) else float(v)
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.bool_,)):
        return bool(v)
    if isinstance(v, (pd.Timestamp, datetime)):
        return v.isoformat()
    return v


def records(df: pd.DataFrame, cols: list[str] | None = None) -> list[dict]:
    d = df[[c for c in (cols or df.columns) if c in df]]
    return [{k: _clean(v) for k, v in r.items()} for r in d.to_dict("records")]


class Service:
    def __init__(self, cfg: dict | None = None, root: Path | None = None, client=None,
                 forecast_as_of: str | None = None, now: datetime | None = None):
        self.cfg = cfg or I.load_config()
        self.root = Path(root or I.ROOT)
        self.client = client
        self.forecast_as_of = forecast_as_of
        self.now = now
        self.state_dir = I.resolve(self.cfg, "state_dir", self.root)
        self.seg, self.seg_meta = I.load_segments(self.cfg, self.root)
        self.risk, self.risk_meta = I.load_risk(self.cfg, self.root)
        self.lights, self.lights_meta = I.load_lights(self.cfg, self.root)
        self.fms = I.load_fms(self.cfg, self.root)
        self.forecast_meta = I.load_forecast_meta(self.cfg, self.root)
        self.synthetic_meta = I.synthetic_meta(self.cfg, self.root)
        self.feedback: dict = {}
        self.queue: list[dict] = []
        self.outcomes: list[dict] = []
        self._scenarios: dict[str, pd.DataFrame] = {}
        self._load_state()
        self.rescore()

    # --- persistence ---------------------------------------------------------------------------
    def _load_state(self):
        p = self.state_dir / "state.json"
        if p.exists():
            s = json.loads(p.read_text(encoding="utf-8"))
            self.feedback, self.queue, self.outcomes = s.get("feedback", {}), s.get("queue", []), s.get("outcomes", [])

    def save(self):
        self.state_dir.mkdir(parents=True, exist_ok=True)
        (self.state_dir / "state.json").write_text(
            json.dumps({"feedback": self.feedback, "queue": self.queue, "outcomes": self.outcomes}, indent=1, default=str),
            encoding="utf-8")

    def reset(self):
        self.feedback, self.queue, self.outcomes = {}, [], []
        self.save()
        self.rescore()

    # --- scoring -------------------------------------------------------------------------------
    def rescore(self):
        self.scored = P.score(self.seg, self.risk, self.cfg, self.feedback)
        self.ctx = TR.Context(self.cfg, self.scored, self.lights, self.queue)
        self._scenario_scored: dict[str, pd.DataFrame] = {}

    def scored_for(self, scenario: str | None) -> pd.DataFrame:
        if not scenario:
            return self.scored
        if scenario not in self._scenarios:
            self._scenarios[scenario] = W.apply_scenario(self.risk, self.seg, scenario, self.cfg, root=self.root)
        if scenario not in self._scenario_scored:
            self._scenario_scored[scenario] = P.score(self.seg, self._scenarios[scenario], self.cfg, self.feedback)
        return self._scenario_scored[scenario]

    def freshness(self, forecast_as_of: str | None = None) -> dict:
        return P.freshness(self.cfg, self.forecast_meta, forecast_as_of or self.forecast_as_of, now=self.now)

    @property
    def inputs_mock(self) -> bool:
        return "mock" in (self.seg_meta["kind"], self.risk_meta["kind"])

    def badges(self) -> dict:
        return {"synthetic": True, "mock_inputs": self.inputs_mock,
                "note": "Risk labels, wear and the lighting register are SYNTHETIC (no council data). "
                        + ("Segments or risk are MOCK until lane A and B outputs are merged." if self.inputs_mock else "")}

    # --- reads ---------------------------------------------------------------------------------
    SEG_COLS = ["segment_id", "name", "ward", "highway", "owner", "length_m", "lat", "lon", "urgency", "band", "wear_pct",
                "p7", "p30", "p30_w0", "p30_w1", "p30_w2", "p30_w3", "p30_peak", "p30_rise", "consequence",
                "consequence_text", "treatment", "treatment_label", "treatment_cost_gbp", "reactive_cost_avoided_gbp",
                "avoided_per_gbp", "reason_1", "reason_2", "reason_3", "esal_day", "traffic_note", "bus_stop",
                "in_flood_area", "status", "confirmed_open", "cracking", "weather_source", "model_version", "as_of",
                "labels_synthetic", "wear_synthetic", "inputs_mock", "input_source"]

    def segments(self, ward=None, band=None, scenario=None, geojson=False, limit=None) -> dict:
        s = self.scored_for(scenario)
        if ward:
            s = s[s["ward"] == ward]
        if band:
            s = s[s["band"] == band] if band != "not_scored" else s[~s["scored"]]
        if limit:
            s = s.sort_values("urgency", ascending=False).head(int(limit))
        meta = {"count": len(s), "as_of": self.risk_meta.get("as_of"), "scenario": scenario, **self.badges()}
        if not geojson:
            return {**meta, "segments": records(s, self.SEG_COLS)}
        feats = []
        for r, g in zip(records(s, ["segment_id", "name", "ward", "highway", "urgency", "band", "status", "confirmed_open"]),
                        s["geometry"]):
            feats.append({"type": "Feature", "properties": r,
                          "geometry": {"type": "LineString", "coordinates": [list(c) for c in I._coords(g)]}})
        return {"type": "FeatureCollection", "features": feats, "meta": meta}

    def segment(self, sid: str, scenario=None) -> dict | None:
        s = self.scored_for(scenario)
        r = s[s["segment_id"] == sid]
        if r.empty:
            return None
        out = records(r, self.SEG_COLS)[0]
        out["reasons"] = [x for x in [out.get("reason_1"), out.get("reason_2"), out.get("reason_3")] if x]
        out["data_dates"] = self.data_dates()
        out["reports"] = [q for q in self.queue if q.get("segment_id") == sid]
        out["outcomes"] = [o for o in self.outcomes if o["segment_id"] == sid]
        out["badges"] = self.badges()
        return out

    def locate(self, lat: float, lon: float) -> dict:
        loc = self.ctx.lookup_location(lat, lon)
        if loc.get("status") == "ok" and loc.get("segment_id"):
            loc["segment"] = self.segment(loc["segment_id"])
        return loc

    def data_dates(self) -> dict:
        return {"risk_as_of": self.risk_meta.get("as_of"), "risk_file_retrieved_at": self.risk_meta.get("retrieved_at"),
                "forecast": self.freshness(), "fixmystreet_retrieved_at": self.fms["retrieved_at"].iloc[0] if len(self.fms) else None,
                "synthetic_generated": (self.synthetic_meta or {}).get("generated_at") or (self.synthetic_meta or {}).get("as_of")}

    def plan(self, ward=None, scenario=None, forecast_as_of=None) -> dict:
        s = self.scored_for(scenario)
        p = P.build_plan(s, self.cfg, ward=ward)
        f = self.freshness(forecast_as_of)
        method = (self._scenarios[scenario]["scenario_method"].iloc[0] if scenario else None)
        return {"as_of": self.risk_meta.get("as_of"), "ward": ward, "scenario": scenario, "scenario_method": method,
                "freshness": f, "provisional": f["provisional"], "count": len(p), "costs": self.cfg["costs"],
                **self.badges(), "rows": records(p, P.PLAN_COLS)}

    def lights_view(self, ward=None, due=None, dark=None, limit=500) -> dict:
        L = self.lights.merge(self.seg[["segment_id", "ward", "name"]], on="segment_id", how="left")
        if ward:
            L = L[L["ward"] == ward]
        due_n, dark_n = int(L["due_90d"].sum()), int(L["currently_dark"].sum())
        if due:
            L = L[L["due_90d"] | L["replacement_overdue"]]
        if dark:
            L = L[L["currently_dark"]]
        L = L.sort_values("p_fail_90d", ascending=False).head(limit)
        open_lights = [q for q in self.queue if q["category"] == "streetlight" and q["status"] in ("pending_approval", "approved")]
        return {"count_due_90d": due_n, "count_currently_dark": dark_n, "as_of": str(self.lights["as_of"].iloc[0]) if len(self.lights) else None,
                "synthetic": True, "open_streetlight_reports": open_lights,
                "official_report_url": self.cfg["coverage"]["official_streetlight_url"],
                "lamps": records(L, ["lamp_id", "segment_id", "name", "ward", "lat", "lon", "unit_type", "unit_install_date",
                                     "burn_hours", "p_fail_90d", "predicted_replacement_date", "replacement_overdue",
                                     "due_90d", "currently_dark", "dark_since", "source"])}

    def open_reports(self) -> dict:
        """Currently open real FixMyStreet pothole reports: shown at urgency 100 with their date."""
        f = self.fms
        cutoff = pd.Timestamp(self.now or datetime.now(timezone.utc)).tz_localize(None) - pd.Timedelta(days=self.cfg["triage"]["open_report_days"])
        o = f[(f["status"] == "open") & (f["requested"] >= cutoff)]
        return {"count": len(o), "window_days": self.cfg["triage"]["open_report_days"], "urgency": 100,
                "source": "fixmystreet", "retrieved_at": f["retrieved_at"].iloc[0] if len(f) else None,
                "reports": records(o.assign(reported_at=o["requested"].dt.strftime("%Y-%m-%d")),
                                   ["id", "category", "reported_at", "status", "lat", "lon", "title"])}

    def recent_fms(self, n=20) -> list[dict]:
        f = self.fms.sort_values("requested", ascending=False).head(n)
        return records(f.assign(reported_at=f["requested"].dt.strftime("%Y-%m-%d")), ["id", "category", "reported_at",
                                                                                     "status", "lat", "lon", "title"])

    def sources(self) -> list[dict]:
        out = []
        for m, lic in [(self.seg_meta, LICENCES["segments"]), (self.risk_meta, LICENCES["risk"]),
                       (self.lights_meta, LICENCES["lights"])]:
            out.append({"dataset": m["name"], "path": m["path"], "kind": m["kind"], "retrieved_at": m.get("retrieved_at"),
                        "data_date": m.get("as_of"), "licence": lic,
                        "synthetic": m["name"] in ("risk", "lights") or m["kind"] == "mock",
                        "label": "MOCK" if m["kind"] == "mock" else ("SYNTHETIC" if m["name"] == "lights" else
                                                                       "cached, retrieved " + str(m.get("retrieved_at"))[:10])})
        if len(self.fms):
            out.append({"dataset": "fixmystreet_reports", "path": self.cfg["paths"]["fms_csv"], "kind": "real",
                        "retrieved_at": self.fms["retrieved_at"].iloc[0], "data_date": str(self.fms["requested"].max().date()),
                        "licence": LICENCES["fixmystreet"], "synthetic": False,
                        "label": "cached, retrieved " + str(self.fms["retrieved_at"].iloc[0])[:10]})
        if self.synthetic_meta:
            out.append({"dataset": "synthetic_council_data", "path": self.cfg["paths"]["synthetic_dir"], "kind": "synthetic",
                        "retrieved_at": None, "data_date": self.synthetic_meta.get("as_of"), "licence": LICENCES["synthetic"],
                        "synthetic": True, "label": "SYNTHETIC"})
        fr = self.freshness()
        out.append({"dataset": "weather_forecast", "path": self.forecast_meta.get("path"), "kind": "real" if self.forecast_meta["available"] else "missing",
                    "retrieved_at": fr["forecast_retrieved_at"], "data_date": None, "licence": LICENCES["forecast"],
                    "synthetic": False, "label": fr["message"]})
        out.append({"dataset": "repair_costs", "path": "roadsense/prevent/prevent.yaml", "kind": "published", "retrieved_at": None,
                    "data_date": "2025", "licence": LICENCES["costs"], "synthetic": False,
                    "label": "treatment £/m² are ASSUMPTIONS"})
        # lane A writes a manifest of every real source (DfT, BODS, EA, Open-Meteo, ONS) once merged
        man = I.resolve(self.cfg, "processed_dir", self.root) / "sources.json"
        if man.exists():
            for s in json.loads(man.read_text(encoding="utf-8")):
                out.append({**s, "synthetic": False})
        return out

    # --- writes --------------------------------------------------------------------------------
    def triage_report(self, body: dict) -> dict:
        rep = dict(body)
        if rep.get("fms_id") is not None and (rep.get("lat") is None or rep.get("title") is None):
            f = self.fms[self.fms["id"] == int(rep["fms_id"])]
            if f.empty:
                raise KeyError(f"FixMyStreet report {rep['fms_id']} not in the cached pull")
            r = f.iloc[0]
            rep.setdefault("title", r["title"])
            rep["lat"], rep["lon"] = rep.get("lat") or float(r["lat"]), rep.get("lon") or float(r["lon"])
            rep.setdefault("reported_at", r["requested"].isoformat())
            rep.setdefault("report_id", f"fms-{int(r['id'])}")
        rep.setdefault("report_id", f"web-{len(self.queue) + 1:04d}")
        rep.setdefault("reported_at", datetime.now(timezone.utc).date().isoformat())
        image = None
        if rep.get("image_b64"):
            image = (base64.b64decode(rep.pop("image_b64")), rep.pop("image_mime", "image/jpeg"))
        method = rep.pop("method", "auto")
        if any(q["report_id"] == rep["report_id"] and not q.get("merged_into") for q in self.queue):
            rep["report_id"] = f"{rep['report_id']}-r{len(self.queue) + 1}"
        wo = TR.triage(rep, self.ctx, client=self.client, method=method, image=image, root=self.root)
        self.save()
        return wo

    def _find(self, report_id: str) -> dict:
        for q in self.queue:
            if q["report_id"] == report_id:
                return q
        raise KeyError(report_id)

    def approve(self, report_id: str, officer: str = "officer") -> dict:
        q = self._find(report_id)
        if q["status"] not in ("pending_approval",):
            raise ValueError(f"work order {report_id} is {q['status']}, cannot approve")
        q["status"], q["approved_by"] = "approved", officer
        q["approved_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
        if q["category"] == "pothole" and q.get("segment_id"):
            fb = self.feedback.setdefault(q["segment_id"], {})
            fb["urgency_floor"] = float(self.cfg["urgency"]["bands"][self.cfg["triage"]["report_floor_band"]])
            fb["open_report"] = report_id
        self.save()
        self.rescore()
        return {"work_order": q, "segment": self.segment(q["segment_id"]) if q.get("segment_id") else None}

    def reject(self, report_id: str, officer: str = "officer") -> dict:
        q = self._find(report_id)
        q["status"], q["rejected_by"] = "rejected", officer
        self.save()
        return q

    def record_outcome(self, segment_id: str, outcome: str, inspection_date: str | None = None,
                       source: str = "officer", outcome_id: str | None = None, rescore: bool = True) -> dict:
        if outcome not in ("pothole", "cracking", "none"):
            raise ValueError("outcome must be pothole, cracking or none")
        if not (self.scored["segment_id"] == segment_id).any():
            raise KeyError(segment_id)
        before = self.segment(segment_id) if rescore else None
        fb = self.feedback.setdefault(segment_id, {})
        fcfg = self.cfg["feedback"]
        fb.pop("urgency_floor", None)  # inspected: the report hold is replaced by what the crew found
        if outcome == "pothole":
            fb["confirmed_open"] = True
        elif outcome == "cracking":
            fb["cracking"] = True
            fb["p30_multiplier"] = fb.get("p30_multiplier", 1.0) * fcfg["cracking_p30_multiplier"]
        else:
            fb["confirmed_open"] = False
            fb["p30_multiplier"] = fb.get("p30_multiplier", 1.0) * fcfg["none_p30_multiplier"]
        rec = {"outcome_id": outcome_id or f"OUT{len(self.outcomes) + 1:05d}", "segment_id": segment_id, "outcome": outcome,
               "inspection_date": inspection_date or datetime.now(timezone.utc).date().isoformat(), "source": source,
               "is_synthetic": source.startswith("synthetic"),
               "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds")}
        self.outcomes.append(rec)
        for q in self.queue:
            if q.get("segment_id") == segment_id and q["status"] == "approved":
                q["status"], q["outcome"] = "inspected", outcome
        self._append_label(rec)
        if not rescore:
            return {"outcome": rec}
        self.save()
        self.rescore()
        after = self.segment(segment_id)
        return {"outcome": rec, "before": {k: before[k] for k in ("urgency", "band", "p30", "treatment")},
                "after": {k: after[k] for k in ("urgency", "band", "p30", "treatment")}}

    def _append_label(self, rec: dict):
        """Crew outcomes become labels for make retrain (lane B's trainer reads them as extra events)."""
        p = self.state_dir / "outcome_labels.csv"
        self.state_dir.mkdir(parents=True, exist_ok=True)
        pd.DataFrame([rec]).to_csv(p, mode="a", header=not p.exists(), index=False)

    def load_crew_outcomes(self, limit: int | None = None) -> dict:
        p = I.resolve(self.cfg, "synthetic_dir", self.root) / "crew_outcomes.csv"
        if not p.exists():
            raise FileNotFoundError("crew_outcomes.csv not on disk (lane B)")
        c = pd.read_csv(p)
        c = c[c["segment_id"].isin(self.scored["segment_id"])]
        if limit:
            c = c.head(limit)
        done = {o["outcome_id"] for o in self.outcomes}
        n = 0
        for r in c.itertuples():
            if r.outcome_id in done:
                continue
            self.record_outcome(r.segment_id, r.outcome, str(r.inspection_date), source=str(r.source),
                                outcome_id=r.outcome_id, rescore=False)
            n += 1
        self.save()
        self.rescore()
        return {"recorded": n, "synthetic": True}
